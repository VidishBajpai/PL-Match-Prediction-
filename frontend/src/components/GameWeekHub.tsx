import React, { useState, useEffect } from 'react';
import type { GameWeekMatch } from '../types';
import { getClubInfo } from '../data/clubs';
import { ClubBadge } from './ClubBadge';
import { Calendar, AlertTriangle, RefreshCw, Sparkles } from 'lucide-react';

export const GameWeekHub: React.FC = () => {
  const [fixtures, setFixtures] = useState<GameWeekMatch[]>([]);
  const [gameweek, setGameweek] = useState<number>(6);
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);

  const fetchGameWeek = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch('/api/gameweek');
      if (!res.ok) throw new Error('Failed to fetch gameweek data');
      const data = await res.json();
      setFixtures(data.fixtures || []);
      setGameweek(data.gameweek || 6);
    } catch (err: any) {
      console.error(err);
      setError('Could not connect to API gameweek feed.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchGameWeek();
  }, []);

  return (
    <div className="max-w-6xl mx-auto space-y-6 animate-in fade-in duration-500">
      {/* Header Banner */}
      <div className="relative overflow-hidden rounded-3xl bg-slate-900/85 border border-slate-800 p-6 sm:p-8 shadow-2xl backdrop-blur-xl flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div className="absolute top-0 left-0 right-0 h-1 bg-gradient-to-r from-[#00ff85] via-cyan-400 to-[#38003c]" />

        <div>
          <div className="flex items-center gap-2 text-xs font-black text-[#00ff85] uppercase tracking-wider mb-2">
            <Calendar className="w-4 h-4" />
            <span>Active Game-Week Forecast</span>
          </div>
          <h2 className="text-2xl sm:text-4xl font-black text-white tracking-tight">
            Game-Week {gameweek} Fixtures Briefing
          </h2>
          <p className="text-xs sm:text-sm text-slate-400 mt-1 max-w-xl">
            Precomputed quantitative forecasts generated by the Master Tri-Hybrid Model for the upcoming matchday.
          </p>
        </div>

        <button
          onClick={fetchGameWeek}
          disabled={loading}
          className="self-start sm:self-auto bg-slate-800 hover:bg-slate-700 text-slate-200 px-4 py-2.5 rounded-xl text-xs font-black border border-slate-700 flex items-center gap-2 transition-all cursor-pointer shrink-0 disabled:opacity-50"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          <span>Refresh Feed</span>
        </button>
      </div>

      {loading ? (
        <div className="flex flex-col items-center justify-center p-16 text-slate-400 gap-3">
          <RefreshCw className="w-7 h-7 animate-spin text-[#00ff85]" />
          <span className="font-bold text-sm text-slate-300">
            Synthesizing Game-Week {gameweek} projections…
          </span>
        </div>
      ) : error ? (
        <div className="p-4 bg-red-950/70 border border-red-800 text-red-200 rounded-2xl flex items-center gap-3">
          <AlertTriangle className="w-5 h-5 text-red-400 shrink-0" />
          <span className="text-sm font-medium">{error}</span>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {fixtures.map((m) => {
            const homeClub = getClubInfo(m.home_team);
            const awayClub = getClubInfo(m.away_team);

            const homeP = Math.round(m.home_win_prob * 100);
            const drawP = Math.round(m.draw_prob * 100);
            const awayP = Math.max(0, 100 - homeP - drawP);

            return (
              <div
                key={`${m.home_team}-${m.away_team}`}
                className="relative overflow-hidden bg-slate-900/80 p-5 rounded-3xl border border-slate-800/90 hover:border-slate-700 transition-all shadow-xl flex flex-col justify-between group"
              >
                <div>
                  {/* Top Bar: Kickoff & Consensus Chip */}
                  <div className="flex items-center justify-between text-xs mb-4">
                    <span className="font-semibold text-slate-400 bg-slate-950 px-2.5 py-1 rounded-lg border border-slate-800">
                      {m.date}
                    </span>
                    <span className="inline-flex items-center gap-1 font-black text-[#00ff85] bg-[#00ff85]/10 border border-[#00ff85]/25 px-2.5 py-0.5 rounded-full uppercase text-[10px] tracking-wider">
                      <Sparkles className="w-3 h-3" />
                      {m.verdict}
                    </span>
                  </div>

                  {/* Clubs Duel Header */}
                  <div className="grid grid-cols-[1fr,auto,1fr] items-center gap-3 py-2">
                    {/* Home Club */}
                    <div className="flex items-center gap-3 min-w-0">
                      <ClubBadge club={homeClub} size="medium" showGlow={true} />
                      <div className="min-w-0">
                        <span className="font-black text-white text-sm sm:text-base block truncate">
                          {m.home_team}
                        </span>
                        <span className="text-[10px] font-bold text-slate-400">
                          {homeClub.shortName} · Home
                        </span>
                      </div>
                    </div>

                    {/* xG Expectation Score */}
                    <div className="flex flex-col items-center justify-center px-3 py-1.5 rounded-xl bg-slate-950 border border-slate-800 text-center">
                      <span className="font-black text-white text-sm tracking-tight">
                        {m.expected_home_goals.toFixed(2)} - {m.expected_away_goals.toFixed(2)}
                      </span>
                      <span className="text-[9px] font-extrabold text-[#00ff85] uppercase tracking-wider">
                        xG Score
                      </span>
                    </div>

                    {/* Away Club */}
                    <div className="flex items-center justify-end gap-3 min-w-0 text-right">
                      <div className="min-w-0">
                        <span className="font-black text-white text-sm sm:text-base block truncate">
                          {m.away_team}
                        </span>
                        <span className="text-[10px] font-bold text-slate-400">
                          {awayClub.shortName} · Away
                        </span>
                      </div>
                      <ClubBadge club={awayClub} size="medium" showGlow={true} />
                    </div>
                  </div>
                </div>

                {/* Bottom Probability Strip & Scoreline */}
                <div className="mt-4 pt-3 border-t border-slate-800/80 space-y-2">
                  {/* Probability Bar */}
                  <div className="h-2 w-full rounded-full overflow-hidden flex bg-slate-950 border border-slate-800">
                    <div
                      style={{
                        width: `${homeP}%`,
                        backgroundColor: homeClub.primaryColor || '#EF0107',
                      }}
                    />
                    <div style={{ width: `${drawP}%` }} className="bg-slate-600" />
                    <div
                      style={{
                        width: `${awayP}%`,
                        backgroundColor: awayClub.primaryColor || '#034694',
                      }}
                    />
                  </div>

                  <div className="flex justify-between items-center text-[10px] font-bold text-slate-300">
                    <span className="text-white">Home: {homeP}%</span>
                    <span className="text-slate-400">Draw: {drawP}%</span>
                    <span className="text-white">Away: {awayP}%</span>
                  </div>

                  <div className="text-[10px] text-slate-400 truncate">
                    Top Scores: <span className="text-slate-200 font-semibold">{m.top_scores}</span>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
