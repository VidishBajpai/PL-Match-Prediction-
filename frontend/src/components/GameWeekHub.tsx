import { useState, useEffect } from 'react';
import type { GameWeekMatch } from '../types';
import { getClubInfo } from '../data/clubs';
import { Calendar, AlertTriangle, RefreshCw } from 'lucide-react';

export const GameWeekHub: React.FC = () => {
  const [fixtures, setFixtures] = useState<GameWeekMatch[]>([]);
  const [gameweek, setGameweek] = useState<number>(6);
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);

  const fetchGameWeek = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch('/api/gameweek');
      if (!res.ok) throw new Error('Failed to fetch gameweek data');
      const data = await res.json();
      setFixtures(data.fixtures || []);
      setGameweek(data.gameweek || 6);
    } catch (err: any) {
      console.error(err);
      setError('Could not connect to API gameweek feed.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchGameWeek();
  }, []);

  return (
    <div className="max-w-6xl mx-auto space-y-6">
      {/* Header Banner */}
      <div className="bg-gradient-to-r from-[#1b0e30] via-[#24133f] to-[#160a29] p-6 rounded-3xl border border-[#3b2061] shadow-xl flex flex-col sm:flex-row items-center justify-between gap-4">
        <div>
          <div className="flex items-center space-x-2 text-xs font-bold text-[#00ff85] uppercase tracking-wider mb-1">
            <Calendar className="w-4 h-4" />
            <span>Active Game-Week Forecast</span>
          </div>
          <h2 className="text-2xl sm:text-3xl font-black text-white">
            Game-Week {gameweek} Premier League Matchups
          </h2>
          <p className="text-xs sm:text-sm text-slate-400 mt-1">
            Precomputed quantitative forecasts generated by the Master Tri-Hybrid Model.
          </p>
        </div>

        <button
          onClick={fetchGameWeek}
          disabled={loading}
          className="bg-[#2a1448] hover:bg-[#381c61] text-slate-200 px-4 py-2 rounded-xl text-xs font-bold border border-[#4d287d] flex items-center space-x-2 transition-all shrink-0"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          <span>Refresh Feed</span>
        </button>
      </div>

      {loading ? (
        <div className="flex items-center justify-center p-16 text-slate-400">
          <RefreshCw className="w-6 h-6 animate-spin text-[#00ff85] mr-2" />
          <span className="font-semibold text-sm">Loading Game-Week {gameweek} projections...</span>
        </div>
      ) : error ? (
        <div className="p-4 bg-red-950/80 border border-red-800 text-red-200 rounded-2xl flex items-center space-x-2">
          <AlertTriangle className="w-5 h-5 text-red-400" />
          <span className="text-sm font-medium">{error}</span>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {fixtures.map((m) => {
            const homeClub = getClubInfo(m.home_team);
            const awayClub = getClubInfo(m.away_team);

            const homeP = Math.round(m.home_win_prob * 100);
            const drawP = Math.round(m.draw_prob * 100);
            const awayP = Math.round(m.away_win_prob * 100);

            return (
              <div
                key={`${m.home_team}-${m.away_team}`}
                className="bg-[#180e29] p-5 rounded-2xl border border-[#2f1d4b] hover:border-[#4d287d] transition-all shadow-lg flex flex-col justify-between"
              >
                <div>
                  {/* Top Bar: Kickoff & Verdict Badge */}
                  <div className="flex items-center justify-between text-xs mb-3">
                    <span className="font-medium text-slate-400 bg-[#120a1f] px-2.5 py-1 rounded-md border border-[#2d1b4a]">
                      {m.date}
                    </span>
                    <span className="font-extrabold text-[#00ff85] bg-[#00ff85]/10 border border-[#00ff85]/25 px-2.5 py-0.5 rounded-full uppercase text-[11px]">
                      {m.verdict}
                    </span>
                  </div>

                  {/* Clubs Duel Header */}
                  <div className="flex items-center justify-between py-2">
                    {/* Home Club */}
                    <div className="flex items-center space-x-2.5">
                      <span className="text-2xl">{homeClub.badgeEmoji}</span>
                      <div>
                        <span className="font-black text-white text-base block">{m.home_team}</span>
                        <span className="text-[11px] text-slate-400">{homeClub.shortName}</span>
                      </div>
                    </div>

                    {/* xG Expectation */}
                    <div className="text-center px-3 py-1 rounded-lg bg-[#11091d] border border-[#301b4d]">
                      <span className="text-xs font-black text-white">
                        {m.expected_home_goals.toFixed(2)} - {m.expected_away_goals.toFixed(2)}
                      </span>
                      <span className="block text-[9px] uppercase tracking-wider text-slate-400">
                        xG Score
                      </span>
                    </div>

                    {/* Away Club */}
                    <div className="flex items-center space-x-2.5 text-right">
                      <div>
                        <span className="font-black text-white text-base block">{m.away_team}</span>
                        <span className="text-[11px] text-slate-400">{awayClub.shortName}</span>
                      </div>
                      <span className="text-2xl">{awayClub.badgeEmoji}</span>
                    </div>
                  </div>
                </div>

                {/* Bottom Probability Strip & Scoreline */}
                <div className="mt-4 pt-3 border-t border-[#2a1744] space-y-2">
                  {/* Probability Bar */}
                  <div className="h-2 w-full rounded-full overflow-hidden flex bg-[#11091d]">
                    <div style={{ width: `${homeP}%` }} className="bg-[#EF0107]" />
                    <div style={{ width: `${drawP}%` }} className="bg-slate-500" />
                    <div style={{ width: `${awayP}%` }} className="bg-[#034694]" />
                  </div>

                  <div className="flex justify-between items-center text-[11px] font-bold text-slate-300">
                    <span className="text-slate-300">H: {homeP}%</span>
                    <span className="text-slate-400">D: {drawP}%</span>
                    <span className="text-slate-300">A: {awayP}%</span>
                  </div>

                  <div className="text-[10px] text-slate-400 truncate">
                    Top Scores: <span className="text-slate-300 font-semibold">{m.top_scores}</span>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
